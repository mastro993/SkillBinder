//! `crates/design/src/tokens.rs`: the scales as Rust constants, formatted as rustfmt would.
use super::shadow::{Ink, Layer};
use super::spec::Spec;
use super::theme_json::KIT_COLORS;
use anyhow::{Context, bail};
use std::fmt::Write as _;

/// Icon sizes, from `DESIGN.md`'s Layout section. The DESIGN.md format has no token group for
/// them, so they are listed here.
const ICONS: &[(&str, f32, &str)] = &[
    ("xs", 12.0, "Inside a small control."),
    (
        "sm",
        14.0,
        "Inline beside caption text, and in a search field.",
    ),
    ("md", 16.0, "A sidebar or row icon."),
    ("lg", 20.0, "A large glyph, such as an empty state's."),
];

/// Whole-element opacities, from `DESIGN.md`'s Elevation & Depth, Components, and Do's and
/// Don'ts sections. The DESIGN.md format has no token group for them, so they are listed here.
const OPACITIES: &[(&str, f32, &str)] = &[
    ("inactive", 0.5, "An inactive row or control."),
    ("disabled", 0.4, "A disabled control or menu row."),
    (
        "wash",
        0.7,
        "The page color over the window while a change blocks it.",
    ),
];

const HEADER: &str = "\
// @generated by `cargo run -p xtask -- design-tokens` from DESIGN.md. Edit DESIGN.md, not this
// file; `cargo run -p xtask -- verify` fails while the two disagree.

//! The design tokens: the scales `DESIGN.md` specifies, in points. Colors with a GPUI Kit theme
//! slot are in `themes/skillbinder.json` and read through `cx.theme()`; [`color`] holds the rest.

use crate::{Ink, Shadow, Tone, TypeLevel};
use gpui_kit::FontWeight;
";

pub fn render(spec: &Spec) -> anyhow::Result<String> {
    let mut out = HEADER.to_owned();
    let space: Vec<_> = spec
        .spacing
        .iter()
        .map(|(name, value)| (name.as_str(), *value, ""))
        .collect();
    scale(
        &mut out,
        "space",
        "Spacing and fixed heights (`spacing`).",
        &space,
    )?;
    listed(&mut out, "f32", &space)?;
    let radius: Vec<_> = spec
        .rounded
        .iter()
        .map(|(name, value)| (name.as_str(), *value, ""))
        .collect();
    scale(&mut out, "radius", "Corner radii (`rounded`).", &radius)?;
    listed(&mut out, "f32", &radius)?;
    text(&mut out, spec)?;
    scale(&mut out, "icon", "Icon sizes (Layout).", ICONS)?;
    scale(&mut out, "opacity", "Whole-element opacity.", OPACITIES)?;
    elevation(&mut out, spec)?;
    color(&mut out, spec)?;
    Ok(out)
}

/// Ends a module with `ALL`, every constant with its `DESIGN.md` name, for the gallery.
fn listed<T>(out: &mut String, kind: &str, values: &[(&str, T, &str)]) -> anyhow::Result<()> {
    out.truncate(out.len() - "}\n".len());
    let _ = write!(
        out,
        "\n    /// Every value with its `DESIGN.md` name, in order.\n    pub const ALL: &[(&str, {kind})] = &[\n"
    );
    for (name, ..) in values {
        let _ = writeln!(out, "        (\"{name}\", {}),", constant(name)?);
    }
    out.push_str("    ];\n}\n");
    Ok(())
}

fn scale(
    out: &mut String,
    module: &str,
    doc: &str,
    values: &[(&str, f32, &str)],
) -> anyhow::Result<()> {
    let _ = write!(out, "\n/// {doc}\npub mod {module} {{\n");
    for (index, (name, value, note)) in values.iter().enumerate() {
        if index > 0 {
            out.push('\n');
        }
        let note = if note.is_empty() {
            String::new()
        } else {
            format!(" {note}")
        };
        let _ = writeln!(out, "    /// `{name}`.{note}");
        let _ = writeln!(out, "    pub const {}: f32 = {value:?};", constant(name)?);
    }
    out.push_str("}\n");
    Ok(())
}

fn text(out: &mut String, spec: &Spec) -> anyhow::Result<()> {
    out.push_str("\n/// Type levels (`typography`).\npub mod text {\n    use super::{FontWeight, TypeLevel};\n");
    for level in &spec.typography {
        let family = if level.mono { "SF Mono" } else { "SF Pro" };
        let _ = write!(
            out,
            "\n    /// `{}`: {family} {}/{}, line height {}.\n    pub const {}: TypeLevel = TypeLevel {{\n        size: {:?},\n        weight: FontWeight({:?}),\n        line_height: {:?},\n        mono: {},\n    }};\n",
            level.name,
            level.size,
            level.weight,
            level.line_height,
            constant(&level.name)?,
            level.size,
            level.weight,
            level.line_height,
            level.mono,
        );
    }
    out.push_str("}\n");
    let levels: Vec<_> = spec
        .typography
        .iter()
        .map(|level| (level.name.as_str(), (), ""))
        .collect();
    listed(out, "TypeLevel", &levels)
}

/// Each level's shadow layers, as `Shadow`s whose ink is black or a Kit theme color.
fn elevation(out: &mut String, spec: &Spec) -> anyhow::Result<()> {
    // One layer per line, which rustfmt would fold differently for one-layer levels.
    out.push_str("\n/// Shadow layers of each elevation level (`elevation`), in points.\n#[rustfmt::skip]\npub mod elevation {\n    use super::{Ink, Shadow};\n");
    for (name, layers) in &spec.elevation {
        if layers.is_empty() {
            let _ = write!(
                out,
                "\n    /// `{name}`: none.\n    pub const {}: &[Shadow] = &[];\n",
                constant(name)?
            );
            continue;
        }
        let _ = write!(
            out,
            "\n    /// `{name}`.\n    pub const {}: &[Shadow] = &[\n",
            constant(name)?
        );
        for layer in layers {
            let _ = writeln!(out, "        {},", self::layer(layer, spec)?);
        }
        out.push_str("    ];\n");
    }
    out.push_str("}\n");
    let names: Vec<_> = spec
        .elevation
        .iter()
        .map(|(name, _)| (name.as_str(), (), ""))
        .collect();
    listed(out, "&[Shadow]", &names)
}

fn layer(layer: &Layer, spec: &Spec) -> anyhow::Result<String> {
    let ink = match &layer.ink {
        Ink::Black(alpha) => format!("Ink::Black({alpha:?})"),
        Ink::Color { name, alpha } => {
            ensure_color(spec, name)?;
            format!("Ink::Theme(|theme| theme.{}, {alpha:?})", kit_field(name)?)
        }
    };
    Ok(format!(
        "Shadow::new({:?}, {:?}, {:?}, {:?}, {ink})",
        layer.x, layer.y, layer.blur, layer.spread
    ))
}

fn ensure_color(spec: &Spec, name: &str) -> anyhow::Result<()> {
    if spec.colors.iter().any(|color| color.name == name) {
        Ok(())
    } else {
        bail!("elevation uses colors.{name}, which DESIGN.md does not define")
    }
}

/// The Kit theme field holding color `role`: its theme key without `.background`, in snake case.
fn kit_field(role: &str) -> anyhow::Result<String> {
    let (key, _) = KIT_COLORS
        .iter()
        .find(|(_, kit_role)| *kit_role == role)
        .with_context(|| format!("elevation uses colors.{role}, which has no Kit theme key"))?;
    Ok(key.trim_end_matches(".background").replace(['.', '-'], "_"))
}

/// The colors Kit has no theme key for, generated as light and dark Rust colors
/// (DESIGN.md § Implementation).
fn rust_color(name: &str) -> bool {
    matches!(name, "hairline" | "accent-soft" | "accent-soft-foreground")
        || name.ends_with("-text")
        || name.starts_with("preset-")
}

/// The Rust colors, with their light and dark values. Every color goes to exactly one of Kit's
/// theme and this module; one with no destination, or both, fails.
fn color(out: &mut String, spec: &Spec) -> anyhow::Result<()> {
    for color in &spec.colors {
        let kit = KIT_COLORS.iter().any(|(_, role)| *role == color.name);
        match (kit, rust_color(&color.name)) {
            (true, false) | (false, true) => {}
            (false, false) => bail!(
                "colors.{} has no destination: give it a Kit theme key in xtask/src/design_tokens/theme_json.rs or a Rust color in rust.rs, and list it in DESIGN.md § Implementation",
                color.name
            ),
            (true, true) => bail!(
                "colors.{} is both a Kit theme color and a Rust color",
                color.name
            ),
        }
    }
    out.push_str("\n/// Colors GPUI Kit's theme has no slot for (`colors`), light and dark.\npub mod color {\n    use super::Tone;\n");
    let own: Vec<_> = spec
        .colors
        .iter()
        .filter(|color| rust_color(&color.name))
        .collect();
    for color in &own {
        let _ = write!(
            out,
            "\n    /// `{}`.\n    pub const {}: Tone = Tone::new(0x{:06X}, 0x{:06X});\n",
            color.name,
            constant(&color.name)?,
            color.light,
            color.dark,
        );
    }
    out.push_str("}\n");
    let names: Vec<_> = own
        .iter()
        .map(|color| (color.name.as_str(), (), ""))
        .collect();
    listed(out, "Tone", &names)
}

/// `control-sm` → `CONTROL_SM`; a leading count of x's spells them out: `2xs` → `XXS`.
fn constant(name: &str) -> anyhow::Result<String> {
    let name = match name.split_at_checked(1) {
        Some((digit, rest)) if digit.chars().all(|c| c.is_ascii_digit()) => {
            let count: usize = digit.parse().context("digit")?;
            if !rest.starts_with('x') || count < 2 {
                bail!("Token name `{name}` must be like `2xs` when it starts with a digit");
            }
            "x".repeat(count - 1) + rest
        }
        _ => name.to_owned(),
    };
    if !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
        bail!("Token name `{name}` has characters a Rust constant cannot hold");
    }
    Ok(name.replace('-', "_").to_ascii_uppercase())
}
